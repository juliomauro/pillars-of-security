// t(scene, key): looks up the current language from the scene's registry
// (shared Phaser.Data.DataManager across all scenes in the Game instance).
function t(scene, key) {
  const lang = (scene.registry && scene.registry.get('language')) || 'pt';
  return (I18N[lang] && I18N[lang][key]) || I18N.pt[key] || key;
}
